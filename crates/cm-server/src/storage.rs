//! Attachment bytes on the local filesystem (`STORAGE_DIR`). Keys are
//! `<tenant>/<attachment id>`; the database row is the only index. An
//! S3/MinIO adapter can replace this behind the same two functions.

use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use tokio::io::AsyncWriteExt;
use uuid::Uuid;

#[derive(Clone)]
pub struct Storage {
    root: PathBuf,
}

pub struct Stored {
    pub key: String,
    pub size: i64,
    pub sha256: String,
}

#[derive(Debug, thiserror::Error)]
pub enum StorageError {
    #[error("file is larger than the limit")]
    TooLarge,
    #[error(transparent)]
    Io(#[from] std::io::Error),
    #[error("upload interrupted: {0}")]
    Upload(String),
}

impl Storage {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    fn path(&self, key: &str) -> PathBuf {
        self.root.join(key)
    }

    /// Stream an upload to disk, hashing as it goes. Removes the partial file on any failure.
    pub async fn put<S, E>(
        &self,
        tenant: Uuid,
        id: Uuid,
        mut chunks: S,
        limit: u64,
    ) -> Result<Stored, StorageError>
    where
        S: futures_util::Stream<Item = Result<bytes::Bytes, E>> + Unpin,
        E: std::fmt::Display,
    {
        use futures_util::StreamExt;
        let key = format!("{tenant}/{id}");
        let path = self.path(&key);
        if let Some(dir) = path.parent() {
            tokio::fs::create_dir_all(dir).await?;
        }
        let tmp = path.with_extension("part");
        let result: Result<Stored, StorageError> = async {
            let mut f = tokio::fs::File::create(&tmp).await?;
            let mut hasher = Sha256::new();
            let mut size: u64 = 0;
            while let Some(chunk) = chunks.next().await {
                let chunk = chunk.map_err(|e| StorageError::Upload(e.to_string()))?;
                size += chunk.len() as u64;
                if size > limit {
                    return Err(StorageError::TooLarge);
                }
                hasher.update(&chunk);
                f.write_all(&chunk).await?;
            }
            f.sync_all().await?;
            tokio::fs::rename(&tmp, &path).await?;
            let sha256 = hasher
                .finalize()
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect();
            Ok(Stored {
                key: key.clone(),
                size: size as i64,
                sha256,
            })
        }
        .await;
        if result.is_err() {
            let _ = tokio::fs::remove_file(&tmp).await;
        }
        result
    }

    pub async fn open(&self, key: &str) -> std::io::Result<tokio::fs::File> {
        // Keys are generated by us from UUIDs; refuse anything else.
        if key.contains("..") || Path::new(key).is_absolute() {
            return Err(std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "bad key",
            ));
        }
        tokio::fs::File::open(self.path(key)).await
    }

    pub async fn remove(&self, key: &str) {
        let _ = tokio::fs::remove_file(self.path(key)).await;
    }
}
